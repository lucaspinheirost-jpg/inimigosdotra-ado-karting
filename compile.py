import re, glob, os, json, html, sys, unicodedata
root, outp = sys.argv[1], sys.argv[2]

def rd(f):
    b = open(f, 'rb').read()
    try: return b.decode('utf-8')
    except UnicodeDecodeError: return b.decode('cp1252')

races = []
def meta(folder):
    n, d, track = [s.strip() for s in folder.split(' - ')]
    return dict(n=int(n), date=d, track=track)

for f in sorted(glob.glob(os.path.join(root, '*', 'Prova*.html'))):
    t = re.sub(r'<td([^>]*)/>', r'<td\1></td>', rd(f))
    hdr = re.findall(r'<th[^>]*>(.*?)</th>', t, re.S)
    rows = []
    for tr in re.findall(r'<tr>(.*?)</tr>', t, re.S):
        c = [html.unescape(re.sub('<[^>]+>', '', x)).strip() for x in re.findall(r'<td[^>]*>(.*?)</td>', tr, re.S)]
        if c and c[0].isdigit():
            r = dict(zip(hdr, c))
            rows.append([int(r['Pos']), re.sub(r'^\[\d+\]\s*', '', r['Nome']).strip(), int(r['Voltas']), r['Melhor Tempo']])
    races.append(dict(meta(os.path.basename(os.path.dirname(f))), res=rows))

